#!/usr/bin/env python3
"""Export only final, anchored auto-research evidence to the permanent report log.

History is preserved. Scores are copied from the independent audit and frozen
analysis, never estimated from a prefix or regenerated by this publication tool.
"""

import argparse
import copy
from datetime import datetime, timezone
from decimal import Decimal
import hashlib
import json
from pathlib import Path
import re
import types

ARCHIVE_HELPER = Path(__file__).with_name("archive_auto_research.py")
archive = types.ModuleType("auto_research_archive")
archive.__file__ = str(ARCHIVE_HELPER)
exec(
    compile(ARCHIVE_HELPER.read_bytes(), str(ARCHIVE_HELPER), "exec"), archive.__dict__
)
EXPERIMENT = "guidance-auto-research"
PUBLIC_ARCHIVE = "experiments/2026-10-21-auto-research-seed2043/evidence"
REPOSITORY = "https://github.com/eob/ld-clustering"
STYLES = ("short", "redundant-positive", "negative-boundaries")


def require(condition, message):
    if not condition:
        raise ValueError(message)


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def finite_cost(value):
    require(
        isinstance(value, str), "audited dollar amount must remain a decimal string"
    )
    result = Decimal(value)
    require(result.is_finite() and result >= 0, "invalid audited dollar amount")
    return result


def dollar_text(value):
    return format(value.normalize(), "f") if value else "0"


class Publication:
    def __init__(
        self,
        run_root,
        audit_path,
        history_path,
        calibration_path,
        selection_path,
        archive_root,
        anchor,
        commit,
    ):
        self.run = Path(run_root).resolve()
        self.archive = Path(archive_root).resolve()
        require(
            isinstance(commit, str) and re.fullmatch("[0-9a-f]{40}", commit),
            "full evidence commit required",
        )
        self.url = f"{REPOSITORY}/blob/{commit}/{PUBLIC_ARCHIVE}"
        self.publication_source = dict(
            repository=REPOSITORY,
            commit=commit,
            run_path=PUBLIC_ARCHIVE,
            manifest_sha256=anchor,
        )
        archive.verify_archive(self.archive, anchor)
        self.manifest = json.loads((self.archive / "manifest.json").read_bytes())
        self.index = self.manifest["payloads"]["run"]["files"]
        self.audit_path = self.relative(audit_path)
        self.audit = self.read(self.audit_path)
        require(
            self.audit.get("schema_version") == 1
            and self.audit.get("experiment") == EXPERIMENT
            and self.audit.get("status")
            in ("verified", "verified_with_failed_conditions"),
            "final independent audit required",
        )
        require(
            self.audit["source"] == self.manifest["runtime"]["source"],
            "audit runtime differs from anchored archive",
        )
        for name, digest in self.audit["evidence_files"].items():
            require(
                self.index.get(name, {}).get("sha256") == digest,
                "audited file is absent/different in archive: " + name,
            )
            self.raw(name)
        self.protocol = self.read("preregistration/protocol.json")
        require(
            self.protocol["experiment"] == EXPERIMENT
            and self.protocol["schema_version"] == 1
            and sha(self.run / "preregistration/protocol.json")
            == self.audit["protocol_sha256"],
            "protocol binding differs",
        )
        self.registry = self.read("preregistration/conditions.json")
        require(
            self.registry["experiment"] == EXPERIMENT
            and self.registry["schema_version"] == 1
            and sha(self.run / "preregistration/conditions.json")
            == self.protocol["conditions_sha256"],
            "condition registry binding differs",
        )
        self.conditions = {row["id"]: row for row in self.registry["conditions"]}
        self.comparisons = {row["id"]: row for row in self.registry["comparisons"]}
        require(
            len(self.conditions) == len(self.registry["conditions"])
            and len(self.comparisons) == len(self.registry["comparisons"]),
            "duplicate registered design/comparison",
        )
        require(
            set(self.audit["costs"]) <= set(self.conditions)
            and set(self.audit["comparisons"]) <= set(self.comparisons),
            "audit includes unregistered results",
        )
        self.history_path, self.calibration_path, self.selection_path = map(
            self.relative, (history_path, calibration_path, selection_path)
        )
        self.history = self.read(self.history_path)
        self.calibration = self.read(self.calibration_path)
        self.selection = self.read(self.selection_path)
        require(
            self.history["schema_version"] == 1
            and isinstance(self.history["objective"], str)
            and isinstance(self.history["rounds"], list),
            "invalid historical log",
        )
        for name, value in [
            ("calibration", self.calibration),
            ("selection", self.selection),
        ]:
            require(
                value.get("schema_version") == 1
                and value.get("experiment") == EXPERIMENT
                and value["protocol_sha256"] == self.audit["protocol_sha256"],
                name + " identity/protocol differs",
            )
            self.dependency(value["audit_sha256"])
        require(
            self.selection["dataset_manifest_sha256"]
            == self.audit["dataset_manifest_sha256"],
            "selection dataset differs",
        )
        for name, score in self.calibration["within_condition_comparisons"].items():
            require(
                self.audit["comparisons"].get(name) == score,
                "calibration comparison differs from final audit",
            )
        self.validate_selection()
        self.allocated = set()

    def relative(self, path):
        path = Path(path).resolve()
        require(
            path.is_relative_to(self.run), "publication input must be inside run-root"
        )
        return path.relative_to(self.run).as_posix()

    def raw(self, name):
        archive.safe_name(name)
        path = (self.run / name).resolve()
        require(path.is_relative_to(self.run), "publication evidence escapes run-root")
        entry = self.index.get(name)
        require(
            entry is not None
            and path.is_file()
            and path.stat().st_size == entry["bytes"]
            and sha(path) == entry["sha256"],
            "raw publication evidence differs from anchored archive: " + name,
        )
        return path

    def read(self, name, mirror=True):
        path = self.raw(name)
        if mirror:
            readable = "readable/" + name
            copy_path = self.archive / readable
            entry = self.manifest["archive_files"].get(readable)
            require(
                entry is not None
                and copy_path.is_file()
                and copy_path.read_bytes() == path.read_bytes()
                and entry["sha256"] == self.index[name]["sha256"],
                "byte-identical readable evidence missing: " + name,
            )
        return json.loads(path.read_bytes())

    def dependency(self, digest):
        matches = [
            name
            for name, entry in self.index.items()
            if name.endswith(".json") and entry["sha256"] == digest
        ]
        require(matches, "analysis dependency audit is not archived")
        value = self.read(sorted(matches)[0], mirror=False)
        require(
            value.get("experiment") == EXPERIMENT
            and value.get("status") in ("verified", "verified_with_failed_conditions")
            and value["protocol_sha256"] == self.audit["protocol_sha256"]
            and value["dataset_manifest_sha256"]
            == self.audit["dataset_manifest_sha256"]
            and value["source"] == self.audit["source"],
            "analysis dependency audit identity differs",
        )
        for name, metrics in value["comparisons"].items():
            require(
                self.audit["comparisons"].get(name) == metrics,
                "analysis used a stale comparison",
            )
        for name, pin in value["evidence_files"].items():
            require(
                self.audit["evidence_files"].get(name) == pin,
                "analysis dependency evidence is not in final audit",
            )
            self.raw(name)

    def validate_selection(self):
        require(
            set(self.selection["modalities"]) == {"text", "images"},
            "selection must retain both modalities",
        )
        for modality, selected in self.selection["modalities"].items():
            baseline = self.audit["comparisons"].get(f"r2-{modality}-baseline")
            candidates = {
                name: self.audit["comparisons"][comparison]
                for name, round_id in [("compact", "r2"), ("boundary", "r3")]
                if (comparison := f"{round_id}-{modality}-{name}")
                in self.audit["comparisons"]
            }
            require(
                selected["status"]
                in ("ADOPTED", "NOT_ADOPTED", "selection_unavailable"),
                "unknown selection status",
            )
            if selected["status"] == "selection_unavailable":
                require(
                    selected["adopted"] is None
                    and selected["challenger"] is None
                    and selected["ranking"] == []
                    and (baseline is None or not candidates),
                    "selection eligibility contradicts unavailable decision",
                )
                continue
            require(
                selected["challenger"] in ("compact", "boundary")
                and selected["adopted"]
                == (
                    selected["challenger"]
                    if selected["status"] == "ADOPTED"
                    else "baseline"
                ),
                "selection decision was relabelled",
            )
            require(
                baseline is not None and selected["baseline"] == baseline,
                "selection baseline differs from final audit",
            )
            n = baseline["n"]
            require(n > 0, "empty selection cohort")
            names = set()
            for row in selected["ranking"]:
                require(
                    row["name"] in ("compact", "boundary") and row["name"] not in names,
                    "invalid selection ranking identity",
                )
                names.add(row["name"])
                metrics = row["metrics"]
                require(
                    metrics == candidates.get(row["name"]),
                    "selection candidate differs from final audit",
                )
                require(metrics["n"] == n, "selection candidate cohort differs")
                checks = dict(
                    named_improved=metrics["named_id_agreement_count"]
                    > baseline["named_id_agreement_count"],
                    direct_retained=metrics["direct_agreement_count"]
                    >= baseline["direct_agreement_count"],
                    reference_coverage_retained=100
                    * (
                        baseline["reference_assigned_count"]
                        - metrics["reference_assigned_count"]
                    )
                    <= 2 * n,
                    candidate_coverage_retained=100
                    * (
                        baseline["candidate_assigned_count"]
                        - metrics["candidate_assigned_count"]
                    )
                    <= 2 * n,
                )
                require(
                    row["checks"] == checks
                    and type(row["eligible"]) is bool
                    and row["eligible"] == all(checks.values()),
                    "selection eligibility checks contradict audited counts",
                )
            require(
                names == set(candidates) and names,
                "selection ranking omits audited development evidence",
            )
            ranked = sorted(
                selected["ranking"],
                key=lambda row: (
                    row["metrics"]["named_id_agreement_count"],
                    row["metrics"]["direct_agreement_count"],
                    min(
                        row["metrics"]["reference_assigned_count"],
                        row["metrics"]["candidate_assigned_count"],
                    ),
                    row["name"] == "compact",
                ),
                reverse=True,
            )
            eligible = [row for row in ranked if row["eligible"]]
            challenger = (eligible or ranked)[0]["name"]
            require(
                selected["ranking"] == ranked
                and selected["challenger"] == challenger
                and selected["status"] == ("ADOPTED" if eligible else "NOT_ADOPTED")
                and selected["adopted"] == (challenger if eligible else "baseline"),
                "selection eligibility/ranking contradicts frozen decision",
            )
            for key in ("original_catalog", "challenger_catalog", "producer_catalog"):
                if key in selected:
                    pin = selected[key]
                    require(
                        self.index.get(pin["path"], {}).get("sha256") == pin["sha256"],
                        "selected catalog byte pin differs",
                    )
                    self.raw(pin["path"])

    def link(self, name, label):
        self.read(name)
        return dict(label=label, url=self.url + "/readable/" + name)

    def common_links(self):
        return [
            self.link(self.audit_path, "Final independent metrics and API ledger"),
            self.link("preregistration/protocol.json", "Frozen protocol"),
            self.link(
                "preregistration/conditions.json", "Registered designs and source paths"
            ),
            self.link(
                "preregistration/runtime-source-pins.json",
                "Measured source and executable pins",
            ),
        ]

    def complete(self, ids):
        return all(
            self.audit["request_response_bindings"].get(name, {}).get("complete")
            is True
            for name in ids
        )

    def accounting(self, ids, complete):
        require(
            not self.allocated.intersection(ids),
            "API stages were charged to multiple new log rows",
        )
        self.allocated.update(ids)
        rows = [
            self.audit["costs"][name] for name in ids if name in self.audit["costs"]
        ]
        if not rows:
            return None
        total = sum((finite_cost(row["known_cost_usd"]) for row in rows), Decimal(0))
        known = dollar_text(total)
        full = (
            complete
            and len(rows) == len(ids)
            and all(row["cost_complete"] is True for row in rows)
        )
        return dict(
            known_cost_usd=known,
            total_cost_usd=known if full else None,
            cost_complete=bool(full),
        )

    def timestamps(self, ids):
        starts, finishes = [], []
        for name in ids:
            spec = self.conditions[name]
            if spec["output"] in self.audit["evidence_files"]:
                artifact = self.read(spec["output"], mirror=False)
                milliseconds = artifact.get("metadata", {}).get("started_at_unix_ms")
                if type(milliseconds) is int and milliseconds >= 0:
                    starts.append(
                        datetime.fromtimestamp(
                            milliseconds / 1000, timezone.utc
                        ).isoformat()
                    )
            receipt = f'registrations/{spec["phase"]}/terminal/{name}.json'
            if receipt in self.index:
                finished = self.read(receipt, mirror=False).get("finished_at_utc")
                if finished is not None:
                    datetime.fromisoformat(finished.replace("Z", "+00:00"))
                    finishes.append(finished)
        if not starts and not finishes:
            return None
        return dict(
            registered_at=None,
            started_at=min(starts) if starts else None,
            finished_at=max(finishes) if finishes else None,
        )

    def selection_text(self):
        return " ".join(
            f'{modality.capitalize()} selection: {selected["status"]}; adopted: {selected["adopted"] or "unavailable"}; frozen challenger: {selected["challenger"] or "unavailable"}.'
            for modality, selected in self.selection["modalities"].items()
        )

    def metric(self, modality, phase, variants):
        n = self.protocol["data"]["partitions"][phase][modality]["count"]
        rows = []
        for metric in (
            "direct_id_agreement",
            "named_id_agreement",
            "adjusted_rand_index",
            "pairwise_f1",
        ):
            conditions = []
            for label, comparison_id in variants:
                value = self.audit["comparisons"].get(comparison_id)
                if value is not None:
                    require(
                        value["n"] == n,
                        "full comparison denominator differs from frozen cohort",
                    )
                    spec = self.comparisons[comparison_id]
                    require(
                        self.complete([spec["reference"], spec["candidate"]]),
                        "incomplete arms supplied full metrics",
                    )
                    self.read(spec["output"])
                scalar = None
                if value is not None:
                    if metric in ("adjusted_rand_index", "pairwise_f1"):
                        scalar = value["partition"][metric]
                    else:
                        field = (
                            "direct_agreement"
                            if metric == "direct_id_agreement"
                            else "named_id_agreement"
                        )
                        scalar = value[field]
                conditions.append(
                    dict(
                        name=label,
                        value=scalar,
                        llm_coverage=(
                            value["reference_coverage"] if value is not None else None
                        ),
                        ld_coverage=(
                            value["candidate_coverage"] if value is not None else None
                        ),
                        both_other=(
                            value["assigned_other"]["both_other"]
                            if value is not None
                            else None
                        ),
                    )
                )
            rows.append(
                dict(
                    cohort=f'{phase.capitalize()} {"text requests" if modality == "text" else "photographs"}',
                    n=n,
                    metric=metric,
                    conditions=conditions,
                )
            )
        return rows

    def evidence(self, comparison_ids, extra=()):
        links = self.common_links()
        for name in comparison_ids:
            if name in self.audit["comparisons"]:
                links.append(
                    self.link(
                        self.comparisons[name]["output"],
                        name + ": full confusion, pair scores, measurements",
                    )
                )
        for name in extra:
            if name in self.index:
                links.append(self.link(name, Path(name).stem.replace("-", " ")))
        return links

    def calibration_round(self, style):
        specs = [
            row
            for row in self.conditions.values()
            if row["phase"] == "calibration" and row["description_style"] == style
        ]
        require(
            len(specs) == 8,
            "calibration must preserve both backends and all four orders",
        )
        ids = [row["id"] for row in specs]
        grouped = {
            row["mode"]: row
            for row in self.calibration["grouped"]
            if row["style"] == style
        }
        require(set(grouped) == {"llm", "ld"}, "calibration omits a backend")
        n = self.protocol["round1"]["items"] * 4
        values = []
        complete = self.complete(ids)
        for mode, label in [("llm", "Sol"), ("ld", "Decisions")]:
            group = grouped[mode]
            usable = group["status"] == "complete" and self.complete(
                [s["id"] for s in specs if s["mode"] == mode]
            )
            if usable:
                require(
                    group["n"] == n
                    and group["distinct_cases"] == self.protocol["round1"]["items"],
                    "calibration dependent denominator differs",
                )
            complete = complete and usable
            values.append(
                dict(
                    name=label,
                    value=group["accuracy"] if usable else None,
                    llm_coverage=None,
                    ld_coverage=None,
                    both_other=None,
                )
            )
        comparisons = [
            name
            for name, row in self.comparisons.items()
            if row["reference"] in ids and row["candidate"] in ids
        ]
        return dict(
            id="auto-r1-" + style,
            title="Calibration: " + style.replace("-", " "),
            phase="calibration",
            status="complete" if complete else "incomplete",
            design=self.protocol["round1"]["name"]
            + "; description style: "
            + style
            + ".",
            hypothesis=self.protocol["hypotheses"]["mechanism"],
            conditions=[
                "Four cyclic orders of the same constructed cases; K8, one page, stable named IDs and Other last.",
                "The grouped denominator counts dependent assignments, not additional distinct cases. Per-order agreement, coverage, errors and probabilities remain in the full evidence.",
                "This row allocates the recorded API costs of these eight registered classifier stages.",
            ],
            dataset="Synthetic constructed-key cases only; no natural-data accuracy claim.",
            timestamps=self.timestamps(ids),
            measurements=(
                [
                    dict(
                        cohort=f'{self.protocol["round1"]["items"]} constructed cases × four orders (dependent assignments per backend)',
                        n=n,
                        metric="constructed_key_accuracy",
                        conditions=values,
                    )
                ]
                if any(v["value"] is not None for v in values)
                else None
            ),
            accounting=self.accounting(ids, complete),
            decision="Retain all three styles and all four orders; calibration does not select the natural-data challenger.",
            next_question=self.protocol["hypotheses"]["compact"],
            limits=[
                self.protocol["round1"]["interpretation"],
                "This synthetic calibration uses four named options plus Other on one page, with nonconsecutive stable IDs "
                + ", ".join(
                    str(value)
                    for value in sorted(self.protocol["round1"]["stable_ids"].values())
                )
                + ". The earlier natural catalogs use eight or ten named options with consecutive IDs. ID encoding, catalog size and semantics are not held constant; this does not rule out conditional encoding, larger-catalog or semantic effects.",
                "Coding and coding-harness review compute are outside the API ledger.",
            ],
            evidence=self.evidence(comparisons, [self.calibration_path]),
        )

    def natural_round(self, kind):
        if kind == "compact":
            phases = {"round2-generation", "round2-development"}
            variants = [("Original", "r2-{m}-baseline"), ("Compact", "r2-{m}-compact")]
            title, number, phase = (
                "Compact membership on development inputs",
                "r2",
                "adaptive_development",
            )
            hypothesis = self.protocol["hypotheses"]["compact"]
            design = self.protocol["round2"]["name"]
            question = self.protocol["hypotheses"]["boundary"]
        elif kind == "boundary":
            phases = {"round3-generation", "round3-development"}
            variants = [
                ("Original (reused)", "r2-{m}-baseline"),
                ("Compact (reused)", "r2-{m}-compact"),
                ("Boundary", "r3-{m}-boundary"),
            ]
            title, number, phase = (
                "Bounded boundary refinement on development inputs",
                "r3",
                "adaptive_development",
            )
            hypothesis = self.protocol["hypotheses"]["boundary"]
            design = self.protocol["round3"]["name"]
            question = self.protocol["question"]
        else:
            phases = {"confirmation", "repeats"}
            variants = [
                ("Original", "confirmation-{m}-baseline"),
                ("Frozen challenger", "confirmation-{m}-challenger"),
            ]
            title, number, phase = (
                "Untouched confirmation of the frozen challenger",
                "r4",
                "confirmation",
            )
            hypothesis = self.protocol["question"]
            design = "One frozen Original/challenger comparison, with the preselected Sol reference repeats."
            question = "Any later redesign requires a new development protocol and fresh confirmation inputs."
        specs = [row for row in self.conditions.values() if row["phase"] in phases]
        ids = [row["id"] for row in specs]
        require(ids, "registered design stages are missing")
        complete = self.complete(ids)
        measurements, comparisons = [], []
        for modality in ("text", "images"):
            pairs = [(label, name.format(m=modality)) for label, name in variants]
            comparisons.extend(name for _, name in pairs)
            complete = complete and all(
                name in self.audit["comparisons"] for _, name in pairs
            )
            measurements.extend(
                self.metric(
                    modality,
                    "confirmation" if kind == "confirmation" else "development",
                    pairs,
                )
            )
        generation = sum(s["kind"] == "rewrite" for s in specs)
        classification = len(specs) - generation
        if kind == "compact":
            decision = (
                "Proceed to the one registered boundary revision using the bounded blinded development review; retain all Compact results. Final development selection follows the Boundary comparison."
                if complete
                else "Retain the incomplete candidate record. Final development selection uses the available complete candidates."
            )
        elif kind == "boundary":
            decision = "Final development selection: " + self.selection_text()
        else:
            decision = "Frozen before confirmation: " + self.selection_text()
        conditions = [
            f"K8 and canonical stable-ID order; condition-matched Sol and Decisions on identical frozen input IDs.",
            f"API accounting covers {generation} catalog-generation stages and {classification} classifier/repeat stages. Every recorded retry, refusal and failed attempt remains in the ledger.",
            "Per-condition JSON retains full category confusion, pairwise scores, coverage, refusals and cost/time measurements. Concurrent loop times are not added as elapsed time.",
        ]
        if kind == "boundary":
            conditions.append(
                "Original and Compact scores are reused; this row allocates only the new Boundary generation and classification costs."
            )
        if kind == "confirmation":
            conditions.append(
                "The challenger is frozen before confirmation. NOT_ADOPTED remains the development decision even when that challenger is measured here. Reference repeats use their own preselected subset, not the full primary denominator."
            )
        else:
            conditions.append(
                "Development outcomes inform the next description revision and selection; these are adaptive scores, separate from untouched confirmation."
            )
        extra = [self.selection_path] + [
            s["output"]
            for s in specs
            if s["kind"] == "rewrite" or s["phase"] == "repeats"
        ]
        return dict(
            id=f"auto-{number}-{kind}",
            title=title,
            phase=phase,
            status="complete" if complete else "incomplete",
            design=design,
            hypothesis=hypothesis,
            conditions=conditions,
            dataset=self.protocol["data"]["text"]
            + " "
            + self.protocol["data"]["photos"],
            timestamps=self.timestamps(ids),
            measurements=(
                measurements
                if any(
                    c["value"] is not None
                    for row in measurements
                    for c in row["conditions"]
                )
                else None
            ),
            accounting=self.accounting(ids, complete),
            decision=decision,
            next_question=question,
            limits=[
                "Direct agreement includes shared Other; named-ID agreement divides matching named IDs by all items. ARI/pair scores give each Other point its own singleton.",
                "Agreement relative to Sol is not human ground truth. Coding and coding-harness qualitative review compute are outside the API ledger.",
                "Cost scopes differ across historical studies; these rows are not a cross-study additive total.",
            ],
            evidence=self.evidence(comparisons, extra),
        )

    def review(self, path):
        path = Path(path)
        if not path.is_absolute():
            path = self.run / path
        value = self.read(self.relative(path))
        expected = {**self.publication_source, "commit": None, "manifest_sha256": None}
        require(
            value.get("schema_version") == 1 and value.get("source") == expected,
            "review source must use null forward pins and the anchored repository/path",
        )
        provenance = value.get("provenance_files")
        require(
            isinstance(provenance, dict) and provenance, "review provenance required"
        )
        for name, digest in provenance.items():
            require(
                isinstance(digest, str)
                and re.fullmatch("[0-9a-f]{64}", digest)
                and self.index.get(name, {}).get("sha256") == digest,
                "review provenance differs from anchored archive: " + name,
            )
            self.raw(name)
        value["source"] = copy.deepcopy(self.publication_source)
        return value

    def build(self, review_publication=None):
        result = copy.deepcopy(self.history)
        rows = [self.calibration_round(style) for style in STYLES]
        rows.extend(
            self.natural_round(kind) for kind in ("compact", "boundary", "confirmation")
        )
        require(
            self.allocated == set(self.conditions),
            "a registered design was omitted from the permanent log",
        )
        result["rounds"].extend(rows)
        require(
            len({row["id"] for row in result["rounds"]}) == len(result["rounds"]),
            "historical/new log IDs collide",
        )
        date = datetime.fromisoformat(
            self.manifest["created_at_utc"].replace("Z", "+00:00")
        )
        result["updated_at"] = date.date().isoformat()
        if review_publication is not None:
            result["review"] = self.review(review_publication)
            result["rounds"][-1]["limits"].append(
                "Review examples and provenance are copied from sealed evidence; public links point to the verified archive."
            )
        return result


def export_publication(
    run_root,
    audit,
    history,
    calibration_analysis,
    selection,
    archive_root,
    archive_manifest_sha256,
    repository_commit,
    output,
    review_publication=None,
):
    output = Path(output).resolve()
    require(not output.exists(), "publication output must be fresh")
    require(
        not output.is_relative_to(Path(archive_root).resolve())
        and not output.is_relative_to(Path(run_root).resolve()),
        "publication output must stay outside frozen evidence roots",
    )
    publication = Publication(
        run_root,
        audit,
        history,
        calibration_analysis,
        selection,
        archive_root,
        archive_manifest_sha256,
        repository_commit,
    ).build(review_publication)
    body = (
        json.dumps(publication, ensure_ascii=False, indent=2, allow_nan=False).encode()
        + b"\n"
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("xb") as target:
        target.write(body)
    return publication


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in (
        "run-root",
        "audit",
        "history",
        "calibration-analysis",
        "selection",
        "archive-root",
        "output",
    ):
        parser.add_argument("--" + name, required=True, type=Path)
    for name in ("archive-manifest-sha256", "repository-commit"):
        parser.add_argument("--" + name, required=True)
    parser.add_argument(
        "--review-publication",
        type=Path,
        help="Optional anchored RUN-relative review DTO; null forward source pins are filled at export.",
    )
    args = parser.parse_args()
    result = export_publication(
        args.run_root,
        args.audit,
        args.history,
        args.calibration_analysis,
        args.selection,
        args.archive_root,
        args.archive_manifest_sha256,
        args.repository_commit,
        args.output,
        args.review_publication,
    )
    print(
        json.dumps(
            dict(
                status="exported", rounds=len(result["rounds"]), output=str(args.output)
            )
        )
    )


if __name__ == "__main__":
    main()
